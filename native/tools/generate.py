"""Deterministic fixed graph regeneration from checked-in layout/graph specs.
Weights are separate pinned deployment assets; no ML framework is imported.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path

from graph import Generator

ROOT = Path(__file__).resolve().parents[1]


def generate(stage):
    name, function = (
        ("recognizer", "recognize") if stage == "rec" else ("detector", "detect")
    )
    spec = ROOT / "models/spec"
    layout = json.loads((spec / f"{stage}-layout.json").read_text())
    graph = (spec / f"{stage}-graph.json").read_bytes()
    if hashlib.sha256(graph).hexdigest() != layout["source_graph"]:
        raise RuntimeError(
            "Frozen graph fingerprint changed; model requalification required"
        )
    assets = json.loads((ROOT / "models/manifest.json").read_text())["files"]
    if layout["weights_sha256"] != assets[f"{name}.weights"]:
        raise RuntimeError("Layout and deployed weight fingerprints disagree")
    size = (ROOT.parent / ".build/models/native" / f"{name}.weights").stat().st_size
    for tensor in layout["tensors"].values():
        if not (
            tensor["offset"] >= 64
            and tensor["offset"] % 64 == 0
            and math.prod(tensor["shape"]) * 4 == tensor["bytes"]
            and tensor["offset"] + tensor["bytes"] <= size
        ):
            raise RuntimeError("Invalid frozen tensor layout")
    body, _ = Generator(layout["tensors"]).generate(json.loads(graph), name)
    if stage == "rec":
        condition = "x.shape.size()==4 && x.shape[0]>=1 && x.shape[0]<=6 && x.shape[1]==3 && x.shape[2]==48 && x.shape[3]>=320 && x.shape[3]<=4096"
        message = "Recognizer requires N=1..6,C=3,H=48,W=320..4096"
        footer = f'''const char* weights_sha256() {{ return "{assets["recognizer.weights"]}"; }}
size_t weights_bytes() {{ return {size}; }}
const char* dictionary_sha256() {{ return "{assets["characters.bin"]}"; }}'''
    else:
        condition = "x.shape.size()==4 && x.shape[0]==1 && x.shape[1]==3 && x.shape[2]>=32 && x.shape[2]<=1280 && x.shape[3]>=32 && x.shape[3]<=1280 && x.shape[2]%32==0 && x.shape[3]%32==0"
        message = "Detector requires batch-one NCHW, multiples of 32, max 1280"
        footer = f'''const char* detector_sha256() {{ return "{assets["detector.weights"]}"; }}
size_t detector_bytes() {{ return {size}; }}'''
    return (
        ROOT / "models" / f"{name}.cpp",
        f'''// Generated by native/tools/generate.py. Do not hand-edit.
#include "engine.hpp"
namespace textpicker {{
Tensor {function}(const Tensor& x,const Weights& weights,Trace* trace) {{
 require({condition},"{message}");
 {body}
}}
{footer}
}}
''',
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for stage in ["rec", "det"]:
        path, code = generate(stage)
        if options.check:
            if path.read_text() != code:
                raise RuntimeError(
                    f"Stale generated source: {path.name}; run native/tools/generate.py"
                )
        else:
            path.write_text(code)
    print(
        "Native generated graphs: verified"
        if options.check
        else "Native generated graphs: updated"
    )


if __name__ == "__main__":
    main()
